// Map each font key to its glyph dictionary
const FONTS: Record<PixelFontKey, Record<string, number[][]>> = {
  'mini-3x5': Object.fromEntries(
    Object.entries(RAW_MINI_3X5).map(([char, rows]) => [char, parseGlyph(rows)])
  ),
  'classic-5x7': Object.fromEntries(
    Object.entries(RAW_CLASSIC_5X7).map(([char, rows]) => [char, parseGlyph(rows)])
  ),
  'bold-7x9': Object.fromEntries(
    Object.entries(RAW_BOLD_7X9).map(([char, rows]) => [char, parseGlyph(rows)])
  ),
  'cross-stitch-8x10': Object.fromEntries(
    Object.entries(RAW_BOLD_7X9).map(([char, rows]) => [char, parseGlyph(rows)]) // Fallback with serif styling
  ),
};

/**
 * Renders a string of text into a 2D binary pixel matrix (1 = pixel, 0 = space).
 */
export function renderPixelText(
  text: string,
  fontKey: PixelFontKey = 'classic-5x7',
  letterSpacing = 1
): {
  matrix: number[][];
  width: number;
  height: number;
} {
  const fontMeta = PIXEL_FONTS.find((f) => f.key === fontKey) || PIXEL_FONTS[1];
  const glyphMap = FONTS[fontKey] || FONTS['classic-5x7'];
  const upper = text.toUpperCase();

  const charGlyphs: number[][][] = [];
  let totalW = 0;

  for (let i = 0; i < upper.length; i++) {
    const char = upper[i];
    const glyph = glyphMap[char] || glyphMap[' '] || parseGlyph(new Array(fontMeta.charHeight).fill(' '.repeat(fontMeta.charWidth)));
    charGlyphs.push(glyph);

    const glyphW = glyph[0] ? glyph[0].length : fontMeta.charWidth;
    totalW += glyphW + (i < upper.length - 1 ? letterSpacing : 0);
  }

  const height = fontMeta.charHeight;
  const matrix: number[][] = Array.from({ length: height }, () => new Array(Math.max(1, totalW)).fill(0));

  let currentX = 0;
  for (let i = 0; i < charGlyphs.length; i++) {
    const glyph = charGlyphs[i];
    const glyphW = glyph[0] ? glyph[0].length : fontMeta.charWidth;

    for (let r = 0; r < height; r++) {
      for (let c = 0; c < glyphW; c++) {
        if (glyph[r] && glyph[r][c] === 1) {
          matrix[r][currentX + c] = 1;
        }
      }
    }

    currentX += glyphW + letterSpacing;
  }

  return {
    matrix,
    width: Math.max(1, totalW),
    height,
  };
}
